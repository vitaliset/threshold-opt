"""K-decay-exponent summary table for the synthetic Lemma verification.

For each perturbation radius ``r`` and cost configuration in the
synthetic sweep (Symmetric 0/1, Asymmetric 2x/5x/10x), the per-K
seed-averaged ratio ``E_p[E_u[(g(p)^T u)^2]] / E_p[||g(p)||^2]`` is
regressed against ``log(K - 1)`` by ordinary least squares. The
Lemma "dimensional dilution" predicts this ratio equals
``r^2 / (K - 1)`` at leading order in r, so the negative slope
``gamma`` should equal 1 exactly (for the linearised quantity,
which is the lemma's leading-order term). The table reports
``gamma`` and its OLS 95% CI at the smallest and largest swept r
to show the prediction holds uniformly across r and cost matrices.

Emits ``tex/tables/lemma_test.tex``.

Usage:
    uv run python -m experiments.analysis.generate_lemma_test_table
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO_ROOT / "experiments" / "results"
TABLE_DIR = REPO_ROOT / "tex" / "tables"

PARQUET_GLOB = "run_results_lemma_test_*/results_lemma_test_*.parquet"
OUTPUT_PATH = TABLE_DIR / "lemma_test.tex"

COST_ORDER = (
    "Symmetric",
    "Asymmetric 2x",
    "Asymmetric 5x",
    "Asymmetric 10x",
)
COST_LATEX = {
    "Symmetric": r"Symmetric $0/1$",
    "Asymmetric 2x": r"Asymmetric $2\times$",
    "Asymmetric 5x": r"Asymmetric $5\times$",
    "Asymmetric 10x": r"Asymmetric $10\times$",
}

Z_95 = 1.96


def _load_latest() -> pd.DataFrame:
    files = sorted(RESULTS_DIR.glob(PARQUET_GLOB))
    if not files:
        raise FileNotFoundError(
            f"No lemma-test parquet matching {PARQUET_GLOB} in {RESULTS_DIR}"
        )
    return pd.read_parquet(files[-1])


def _fit_one(sub: pd.DataFrame) -> tuple[float, float]:
    """Fit gamma of dphi_sq_linear/g_sq against log(K-1) for one
    (cost, r) slice.

    Returns (gamma_hat, se_beta).
    """
    sub = sub.assign(ratio=lambda d: d["dphi_sq_linear"] / d["g_sq"])
    means = sub.groupby("K")["ratio"].mean()
    Ks = sorted(int(k) for k in means.index)
    x = np.log(np.array(Ks, dtype=float) - 1.0)
    y = np.log(means.reindex(Ks).to_numpy(dtype=float))
    finite = np.isfinite(x) & np.isfinite(y)
    x = x[finite]
    y = y[finite]
    n = len(x)
    x_mean = x.mean()
    ss_x = float(((x - x_mean) ** 2).sum())
    beta = float(((x - x_mean) * y).sum() / ss_x)
    alpha = float(y.mean() - beta * x_mean)
    y_hat = alpha + beta * x
    ss_resid = float(((y - y_hat) ** 2).sum())
    sigma2 = ss_resid / (n - 2)
    se_beta = float(np.sqrt(sigma2 / ss_x))
    return -beta, se_beta


def _fmt(gamma: float, se: float) -> str:
    """Format gamma with normal-approx 95% CI to three decimals."""
    lo = gamma - Z_95 * se
    hi = gamma + Z_95 * se
    return f"${gamma:.3f}$ $[{lo:.3f},\\,{hi:.3f}]$"


def build() -> Path:
    df = _load_latest()
    present_costs = set(df["cost_name"].unique())
    costs = [c for c in COST_ORDER if c in present_costs]
    if not costs:
        raise KeyError(
            f"No expected cost configurations in parquet: {present_costs}"
        )

    rs = sorted(float(r) for r in df["r"].unique() if r > 0)
    r_min = rs[0]
    r_max = rs[-1]

    rows: list[str] = []
    for cost in costs:
        gh_min, se_min = _fit_one(
            df[(df["cost_name"] == cost) & (df["r"] == r_min)]
        )
        gh_max, se_max = _fit_one(
            df[(df["cost_name"] == cost) & (df["r"] == r_max)]
        )
        rows.append(
            f"    {COST_LATEX[cost]} & {_fmt(gh_min, se_min)}"
            f" & {_fmt(gh_max, se_max)} \\\\"
        )

    body = "\n".join(rows)
    tex = (
        "% Auto-generated by"
        " experiments.analysis.generate_lemma_test_table"
        " --- do not edit.\n"
        "\\begin{tabular}{lcc}\n"
        "    \\toprule\n"
        "    Cost configuration"
        f" & $\\widehat{{\\gamma}}$ at $r={r_min:g}$"
        f" & $\\widehat{{\\gamma}}$ at $r={r_max:g}$ \\\\\n"
        "    \\midrule\n"
        f"{body}\n"
        "    \\bottomrule\n"
        "\\end{tabular}%\n"
    )
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(tex, encoding="utf-8")
    print(f"  Wrote {OUTPUT_PATH}")
    return OUTPUT_PATH


if __name__ == "__main__":
    build()

def compute_stats(
    sampler: SamplerFn,
    K: int,
    n_samples: int = 500,
    seed: int = 42,
    grid_bary: np.ndarray | None = None,
) -> dict[str, float]:
    """Per-sampler statistics averaged over *n_samples* draws.

    Metrics (parameterisation-agnostic — work for both Voronoi-centroid
    and affine-bias predictors):
        vertex_self_rate
                        Fraction of samples where ``predict(eye(K))``
                        equals ``[0, 1, ..., K-1]`` (every pure-class
                        probability vertex classified as its own class).
        mean_entropy_grid
                        Mean across a simplex grid of the normalised
                        (base-K) Shannon entropy of the class-fraction
                        vector at each grid point. 0 when every sample
                        decodes the simplex identically; 1 when every
                        grid point is classified uniformly across
                        classes. This is the grid-average analogue of
                        the greyscale darkness in the overlay figure.
        partition_deviation
                        Mean fraction of a simplex grid whose predicted
                        class differs from argmax. 0 = identical to
                        argmax; grows as the sampler explores further
                        from the argmax baseline.
        rejection_rate  Fraction of sampler calls that raised
                        SamplerExhausted (no valid draw within the
                        retry budget). Other metrics are averaged only
                        over successful draws.
    """
    rng = np.random.default_rng(seed)
    edges = np.eye(K)
    if grid_bary is None:
        # Cheap random sample of the simplex for partition metrics.
        grid_rng = np.random.default_rng(seed + 1)
        grid_bary = grid_rng.dirichlet(np.ones(K), size=1024)
    argmax_preds = np.argmax(grid_bary, axis=1)
    n_grid = grid_bary.shape[0]

    vertex_self_hits = 0
    rejection_hits = 0
    deviation_sum = 0.0
    grid_class_counts = np.zeros((n_grid, K))
    grid_idx = np.arange(n_grid)
    successful_draws = 0

    for _ in range(n_samples):
        try:
            predictor = sampler(rng, K)
        except SamplerExhausted:
            rejection_hits += 1
            continue
        successful_draws += 1
        vertex_preds = predictor(edges)
        if np.array_equal(vertex_preds, np.arange(K)):
            vertex_self_hits += 1
        preds_on_grid = predictor(grid_bary)
        deviation_sum += float(np.mean(preds_on_grid != argmax_preds))
        grid_class_counts[grid_idx, preds_on_grid] += 1

    if successful_draws > 0:
        grid_fractions = grid_class_counts / successful_draws
        with np.errstate(divide="ignore", invalid="ignore"):
            log_f = np.log2(grid_fractions)
        log_f = np.where(grid_fractions > 0, log_f, 0.0)
        entropy_per_point = -np.sum(grid_fractions * log_f, axis=1)
        if K > 1:
            entropy_per_point = entropy_per_point / np.log2(K)
        mean_entropy_grid = float(entropy_per_point.mean())
        vertex_self_rate = vertex_self_hits / successful_draws
        partition_deviation = deviation_sum / successful_draws
    else:
        mean_entropy_grid = float("nan")
        vertex_self_rate = float("nan")
        partition_deviation = float("nan")

    return {
        "vertex_self_rate": vertex_self_rate,
        "mean_entropy_grid": mean_entropy_grid,
        "partition_deviation": partition_deviation,
        "rejection_rate": rejection_hits / n_samples,
    }


def _single_trial_task(
    key: tuple,
    trial_idx: int,
    sampler: SamplerFn,
    K: int,
    n_samples_per_trial: int,
    seed: int,
) -> tuple[tuple, int, dict[str, float]]:
    """Worker wrapper: run compute_stats for one (sampler, K, trial) slot."""
    stats = compute_stats(sampler, K, n_samples=n_samples_per_trial, seed=seed)
    return key, trial_idx, stats


@contextlib.contextmanager
def _tqdm_joblib(tqdm_object):
    """Patch joblib so a tqdm bar advances on task completion."""

    class _Callback(joblib.parallel.BatchCompletionCallBack):
        def __call__(self, *args, **kwargs):
            tqdm_object.update(n=self.batch_size)
            return super().__call__(*args, **kwargs)

    old = joblib.parallel.BatchCompletionCallBack
    joblib.parallel.BatchCompletionCallBack = _Callback
    try:
        yield tqdm_object
    finally:
        joblib.parallel.BatchCompletionCallBack = old
        tqdm_object.close()


def _run_trials_parallel(
    outer_tasks: list[tuple[tuple, SamplerFn, int]],
    n_trials: int,
    n_samples_per_trial: int,
    base_seed: int,
    n_jobs: int,
    desc: str,
) -> dict[tuple, dict[str, np.ndarray]]:
    """Dispatch trial-level tasks across joblib workers and regroup by key.

    Flattens ``outer_tasks`` (one entry per ``(sampler, K)`` slot) into
    ``n_trials``-many trial tasks per slot so joblib can load-balance
    across the slow long-pole slots instead of serializing trials inside
    them. Seeds follow ``base_seed + t`` so results are independent of
    the chosen parallelism granularity.
    """
    flat = [
        (key, t, sampler, K, base_seed + t)
        for key, sampler, K in outer_tasks
        for t in range(n_trials)
    ]
    with _tqdm_joblib(tqdm(total=len(flat), desc=desc, unit="trial")):
        completed = joblib.Parallel(n_jobs=n_jobs)(
            joblib.delayed(_single_trial_task)(
                key, t, sampler, K, n_samples_per_trial, seed
            )
            for key, t, sampler, K, seed in flat
        )

    grouped: dict[tuple, list[tuple[int, dict[str, float]]]] = {}
    for key, t, stats in completed:
        grouped.setdefault(key, []).append((t, stats))

    trials_by_key: dict[tuple, dict[str, np.ndarray]] = {}
    for key, items in grouped.items():
        items.sort(key=lambda kv: kv[0])
        per_metric: dict[str, list[float]] = {}
        for _, stats in items:
            for m, v in stats.items():
                per_metric.setdefault(m, []).append(v)
        trials_by_key[key] = {
            m: np.asarray(vs) for m, vs in per_metric.items()
        }
    return trials_by_key


# Samplers to include in the K-sweep metrics plot. Rejection is excluded

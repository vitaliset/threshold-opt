# ---------------------------------------------------------------------------
# Samplers: each returns a (K, K) centroid matrix on the K-simplex.
# ---------------------------------------------------------------------------


def _argmin_nearest(points: np.ndarray, centroids: np.ndarray) -> np.ndarray:
    """For each row in *points*, index of the nearest row in *centroids*."""
    diffs = points[:, None, :] - centroids[None, :, :]
    return np.argmin(np.sum(diffs**2, axis=-1), axis=1)


# A Predictor maps probability rows (N, K) -> predicted class indices (N,).
Predictor = Callable[[np.ndarray], np.ndarray]
# A Sampler draws one strategy instance and returns its predictor.
SamplerFn = Callable[[np.random.Generator, int], Predictor]


def _voronoi_predictor(centroids: np.ndarray) -> Predictor:
    def predict(grid: np.ndarray) -> np.ndarray:
        return _argmin_nearest(grid, centroids)

    return predict


def _parallel_shift_predictor(biases: np.ndarray) -> Predictor:
    """MultiDimThreshold decoder: argmax_k (p_k - b_k)."""

    def predict(grid: np.ndarray) -> np.ndarray:
        return np.argmax(grid - biases, axis=1)

    return predict


def _threshold_ratio_predictor(thresholds: np.ndarray) -> Predictor:
    """ThresholdRatio decoder: argmax_k (p_k / t_k)."""

    def predict(grid: np.ndarray) -> np.ndarray:
        return np.argmax(grid / thresholds, axis=1)

    return predict


def _full_matrix_predictor(A: np.ndarray) -> Predictor:
    """FullMatrix decoder: argmin_i (p @ A)_i, matching the production
    FullMatrixPartitioningStrategy.predict convention.
    """

    def predict(grid: np.ndarray) -> np.ndarray:
        return np.argmin(grid @ A, axis=1)

    return predict


class SamplerExhausted(RuntimeError):
    """Raised by retry-based samplers when no valid draw is accepted."""


def sample_rejection(
    rng: np.random.Generator, K: int, max_retries: int = 100
) -> Predictor:
    """Rejection sampler: Dirichlet(1/K), accept if the nearest-vertex
    assignment is a bijection; raise after max_retries failures."""
    edges = np.identity(K)
    alpha = np.full(K, 1.0 / K)
    for _ in range(max_retries):
        centroids = rng.dirichlet(alpha, size=K)
        mapping = _argmin_nearest(edges, centroids)
        if len(np.unique(mapping)) == K:
            return _voronoi_predictor(centroids[mapping])
    raise SamplerExhausted(
        f"Rejection sampler exhausted {max_retries} retries at K={K}"
    )


def sample_hungarian(rng: np.random.Generator, K: int) -> Predictor:
    """Dirichlet(1/K) + Hungarian bijection. Always valid,
    does not preserve 'nearest-from-vertex is identity'."""
    centroids = rng.dirichlet(np.full(K, 1.0 / K), size=K)
    cost = np.sum(
        (np.eye(K)[:, None, :] - centroids[None, :, :]) ** 2, axis=-1
    )
    _, col = linear_sum_assignment(cost)
    return _voronoi_predictor(centroids[col])


def sample_swap_max(rng: np.random.Generator, K: int) -> Predictor:
    """Dirichlet(1/K) + 'swap argmax into position i' for each centroid.
    Guarantees strict max at i but not nearest-from-vertex for K >= 10."""
    centroids = np.empty((K, K))
    alpha = np.full(K, 1.0 / K)
    for i in range(K):
        c = rng.dirichlet(alpha)
        j = int(c.argmax())
        c[[i, j]] = c[[j, i]]
        centroids[i] = c
    return _voronoi_predictor(centroids)


def sample_shrink(
    rng: np.random.Generator, K: int, lam: float = 0.5
) -> Predictor:
    """Shrink-to-vertex: c_i = (1 - lam) * e_i + lam * Dirichlet(1)."""
    raw = rng.dirichlet(np.ones(K), size=K)
    centroids = (1.0 - lam) * np.eye(K) + lam * raw
    return _voronoi_predictor(centroids)


def sample_argmax(rng: np.random.Generator, K: int) -> Predictor:
    """Reference baseline: centroids = identity (pure argmax strategy)."""
    del rng
    return _voronoi_predictor(np.eye(K))


def sample_concentrated_dirichlet(
    rng: np.random.Generator, K: int, beta: float = 5.0
) -> Predictor:
    """Each c_i drawn from Dir(alpha_i) where alpha_i[i]=beta, else 1."""
    centroids = np.empty((K, K))
    for i in range(K):
        alpha = np.ones(K)
        alpha[i] = beta
        centroids[i] = rng.dirichlet(alpha)
    return _voronoi_predictor(centroids)


def sample_sequential_dsq(
    rng: np.random.Generator,
    K: int,
    alpha: float = 1.0,
    max_retries: int = 100,
) -> Predictor:
    """Sequential sampling with strict d² constraint.

    The analysis in the appendix uses max_retries=100 to match the
    rejection baseline's budget; the production implementation in
    src/threshold_opt/multiclass_strategies.py uses 500 as a
    conservative headroom.
    """
    centroids = np.empty((K, K))

    def _dsq(vertex_idx: int, c: np.ndarray) -> float:
        return 1.0 - 2.0 * c[vertex_idx] + float(c @ c)

    for i in range(K):
        for _ in range(max_retries):
            c = rng.dirichlet(np.full(K, alpha))
            j = int(c.argmax())
            c[[i, j]] = c[[j, i]]
            ok = True
            for k in range(i):
                if _dsq(k, c) <= _dsq(k, centroids[k]):
                    ok = False
                    break
                if _dsq(i, c) >= _dsq(i, centroids[k]):
                    ok = False
                    break
            if ok:
                centroids[i] = c
                break
        else:
            raise SamplerExhausted(
                f"Sequential d^2 sampler exhausted {max_retries} retries"
                f" placing centroid {i} at K={K}"
            )
    return _voronoi_predictor(centroids)


# ---------------------------------------------------------------------------
# Affine-family samplers: biases and threshold ratios, not centroids.
# ---------------------------------------------------------------------------


def sample_multidim_threshold(
    rng: np.random.Generator, K: int, scale: float = 1.0
) -> Predictor:
    """MultiDimThreshold biases, matching the Chapter 4 experiment ranges.

    MultidimensionalThresholdStrategy uses a RandomSearchOptimizer with
    bounds=(-1, 1) over K-1 bias parameters; class 0's bias is pinned at
    0 (see src/threshold_opt/multiclass_strategies.py). Decision rule
    inside the experiment: argmax_k (p_k + bias_k), which is the same
    sign convention as argmax_k (p_k - bias_k) under bias -> -bias; we
    use the subtractive form of _parallel_shift_predictor here.
    """
    biases = np.empty(K)
    biases[0] = 0.0
    biases[1:] = rng.uniform(-scale, scale, size=K - 1)
    return _parallel_shift_predictor(biases)


def sample_threshold_ratio(
    rng: np.random.Generator, K: int, low: float = 0.01, high: float = 1.5
) -> Predictor:
    """ThresholdRatio per-class divisors, matching Chapter 4 experiments.

    ThresholdRatioMulticlass samples all K divisors from Uniform[0.01, 1.5]
    (no class pinning). Decision rule: argmax_k (p_k / threshold_k); the
    rule is invariant under a common positive rescaling of all K
    thresholds, so no gauge is fixed.
    """
    thresholds = rng.uniform(low, high, size=K)
    return _threshold_ratio_predictor(thresholds)


# ---------------------------------------------------------------------------
# Full-matrix samplers: K^2 free entries, no DLC constraint enforced.
# ---------------------------------------------------------------------------


def sample_full_matrix(
    rng: np.random.Generator, K: int, scale: float = 1.0
) -> Predictor:
    """FullMatrixPartitioning Delta, matching the Chapter 4 experiment ranges.

    FullMatrixPartitioningStrategy parameterises the K x K partition
    matrix as A = A_0 + Delta with Delta sampled in [-1, 1]^{K x K} by
    random search. The anchor is the symmetric 0/1 cost matrix
    A_0 = J - I (the non-decomposable-metric branch, which gives the
    Argmax rule at Delta = 0); the cost-matrix branch is omitted here
    because this analysis is parameterisation-agnostic and has no cost
    matrix in scope. Decision rule: argmin_i (p @ A)_i.
    """
    anchor = np.ones((K, K)) - np.eye(K)
    delta = rng.uniform(-scale, scale, size=(K, K))
    return _full_matrix_predictor(anchor + delta)



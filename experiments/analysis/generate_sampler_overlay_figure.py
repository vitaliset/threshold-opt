"""Generate tex/figures/sampler_partition_overlay.png.

Overlay figure showing the class-assignment regions produced by many
samples from each Voronoi centroid sampler. For every point on the
probability simplex, we colour it by the *empirical distribution of
class assignments across the samples* — blending the three class
colours in proportion to how often each class won at that point.

Interpretation: solid uniform regions mean "every sample agrees this
part of the simplex is class k" (good — the sampler is consistent on
the pure-class regions). Muddy regions mean "samples disagree" — the
sampler is producing configurations that swap classifications here.
The visible footprint shows how much of the simplex each sampler
actually reaches.

Usage:
    uv run python -m experiments.analysis.generate_sampler_overlay_figure
    uv run python -m experiments.analysis.generate_sampler_overlay_figure \\
        --n-samples 500 --grid-n 400

Where to run:
    The default invocation (overlay PNG only) is cheap and fine to run
    locally. The full appendix run with --plot-metrics (the K-sweep up
    to K=100, exposed as ``make figures-sampler-analysis``) is
    CPU-heavy and should be run on the CPU GCP VM, not on a laptop;
    see experiments/cloud/README.md. After the VM run, copy the
    regenerated tex/figures/sampler_metrics_vs_k.tex,
    sampler_rejection_rate.tex, and sampler_partition_overlay.png back
    into the repo.
"""


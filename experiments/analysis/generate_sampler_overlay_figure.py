def _rgb_pgf(rgb: tuple[int, int, int]) -> str:
    """Format an RGB triple as the pgfplots ``{rgb,255:...}`` colour syntax."""
    r, g, b = rgb
    return f"{{rgb,255:red,{r}; green,{g}; blue,{b}}}"


def _addplot_line_errbar(
    color_rgb: tuple[int, int, int],
    line_style: str,
    coords: list[tuple[float, float, float]],
    legend_entry: str | None,
) -> str:
    """Build one ``\\addplot`` block: log-axis line+errorbar series."""
    color_str = _rgb_pgf(color_rgb)
    coords_lines = "\n".join(
        f"        ({x:g}, {y:.6g}) +- (0, {h:.6g})" for x, y, h in coords
    )
    block = (
        "\\addplot[\n"
        f"    color={color_str}, mark=*, mark size=1.2pt,"
        f" line width=0.9pt, {line_style},\n"
        "    error bars/y dir=both, error bars/y explicit,\n"
        "    error bars/error bar style={line width=0.5pt}\n"
        "] coordinates {\n"
        f"{coords_lines}\n"
        "    };"
    )
    if legend_entry is not None:
        block += f"\n\\addlegendentry{{{legend_entry}}}"
    return block


def _sparse_xticklabels(k_values: list[int], label_at: tuple[int, ...]) -> str:
    """Build a pgfplots ``xticklabels`` list with empty entries between
    labelled positions. Avoids overlap on dense log axes by labelling
    only a sparse subset; data points still sit on tick gridlines."""
    return ",".join(str(k) if k in label_at else "" for k in k_values)



def make_triangle_grid(
    n: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Regular n-by-n Cartesian grid, barycentric coords, and in-triangle mask.

    Triangle vertices (Cartesian):
        v0 (class 0) = (0.5, sqrt(3)/2)   -- top
        v1 (class 1) = (0, 0)             -- bottom-left
        v2 (class 2) = (1, 0)             -- bottom-right
    """
    sqrt3 = math.sqrt(3.0)
    xs = np.linspace(0.0, 1.0, n)
    ys = np.linspace(0.0, sqrt3 / 2.0, n)
    X, Y = np.meshgrid(xs, ys, indexing="xy")
    b0 = 2.0 * Y / sqrt3
    b2 = X - 0.5 * b0
    b1 = 1.0 - b0 - b2
    inside = (b0 >= -1e-9) & (b1 >= -1e-9) & (b2 >= -1e-9)
    bary = np.stack([b0, b1, b2], axis=-1).reshape(-1, 3)
    inside_flat = inside.reshape(-1)
    # Clip slight negatives before feeding to the classifier.
    bary = np.clip(bary, 0.0, None)
    bary /= np.maximum(bary.sum(axis=1, keepdims=True), 1e-12)
    return X, Y, bary, inside_flat


def accumulate_class_fractions(
    sampler: SamplerFn,
    n_samples: int,
    K: int,
    grid_bary: np.ndarray,
    seed: int = 42,
) -> np.ndarray:
    """Run *sampler* *n_samples* times, return per-grid-point class fractions.

    Returns array of shape ``(n_grid_points, K)`` whose rows sum to 1.
    Entry ``[i, k]`` is the fraction of samples for which grid point
    ``i`` was classified as class ``k``.
    """
    rng = np.random.default_rng(seed)
    counts = np.zeros((grid_bary.shape[0], K))
    row_idx = np.arange(grid_bary.shape[0])
    successful = 0
    for _ in range(n_samples):
        try:
            predictor = sampler(rng, K)
        except SamplerExhausted:
            continue
        preds = predictor(grid_bary)
        counts[row_idx, preds] += 1.0
        successful += 1
    if successful == 0:
        return counts  # all zeros → render as white; caller should note
    return counts / successful


def disagreement_greyscale(fractions: np.ndarray) -> np.ndarray:
    """Map per-grid-point class fractions to greyscale RGB by Shannon entropy.

    Returns array of shape ``(n_grid_points, 3)``. The entropy is normalised
    to ``[0, 1]`` (``0`` when one class dominates every draw, ``1`` at the
    uniform distribution over all classes), and the greyscale is
    ``1 - entropy`` per channel so pure regions render white and maximally
    mixed regions render black.
    """
    K = fractions.shape[1]
    with np.errstate(divide="ignore", invalid="ignore"):
        log_f = np.log(fractions)
    log_f = np.where(fractions > 0.0, log_f, 0.0)
    entropy = -np.sum(fractions * log_f, axis=1) / np.log(K)
    grey = np.clip(1.0 - entropy, 0.0, 1.0)
    return np.repeat(grey[:, None], 3, axis=1)



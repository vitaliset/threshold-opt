def render_panel(
    ax,
    X: np.ndarray,
    Y: np.ndarray,
    rgb_flat: np.ndarray,
    inside_flat: np.ndarray,
    title: str,
) -> None:
    n = X.shape[0]
    rgba = np.ones((n * n, 4))
    rgba[inside_flat, :3] = rgb_flat[inside_flat]
    rgba[~inside_flat, 3] = 0.0
    img = rgba.reshape(n, n, 4)
    sqrt3 = math.sqrt(3.0)
    ax.imshow(
        img,
        origin="lower",
        extent=[0.0, 1.0, 0.0, sqrt3 / 2.0],
        aspect="equal",
        interpolation="nearest",
    )
    # Triangle outline.
    tri_x = [0.5, 0.0, 1.0, 0.5]
    tri_y = [sqrt3 / 2.0, 0.0, 0.0, sqrt3 / 2.0]
    ax.plot(tri_x, tri_y, color="black", lw=1.0)
    ax.set_title(title, fontsize=10)
    ax.set_xticks([])
    ax.set_yticks([])
    ax.set_xlim(-0.08, 1.08)
    ax.set_ylim(-0.08, sqrt3 / 2.0 + 0.1)
    for spine in ax.spines.values():
        spine.set_visible(False)



"""Generate the multiclass winning-family percentages quoted in the text.

Writes ``tex/tables/winning_family_summary.tex``: LaTeX macros with the
share of benchmark cells in which only a vector-tuned strategy, both
families, only a Voronoi strategy, or neither family is in the winning
band. Chapter 7 and the conclusion quote these macros.

Usage:
    uv run python -m experiments.analysis.generate_decision_summaries
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from experiments.analysis.generate_tables import (
    SCOPE_CONFIG,
    TABLES_DIR,
    _apply_legacy_strategy_renames,
    _drop_custom_cost_fallback,
    _find_latest_parquet,
    _normalize_balanced_error_objective,
)
from experiments.analysis.generate_win_counts import compute_win_table

OUTPUT_NAME = "winning_family_summary.tex"
CELL_COLUMNS = ["dataset_name", "model_name", "optimization_objective_name"]
VECTOR_TUNED_STRATEGIES = tuple(
    strategy + suffix
    for strategy in (
        "ThresholdRatio",
        "MultidimensionalThreshold",
        "RiskPartitioning",
        "LinearScaling",
    )
    for suffix in ("", "CV")
)
VORONOI_STRATEGIES = ("VoronoiTuning", "VoronoiTuningCV")


def format_percent(percent: float) -> str:
    """Round a percentage the way the text reports win rates.

    Whole percentages, as in the win-count heatmaps, except below 2% and
    above 98%, where one decimal keeps small differences visible.
    """
    if percent < 2 or percent > 98:
        return f"{percent:.1f}"
    return f"{round(percent)}"


def compute_winning_family_split(win_table: pd.DataFrame) -> pd.DataFrame:
    """Count every benchmark cell once, including wins by neither family.

    The winning bands compare against all evaluated strategies. Full-matrix
    and sequential strategies belong to neither family; cells they win stay
    in the denominator. A strategy missing from a cell counts as no win.
    """
    winners = win_table.pivot(
        index=CELL_COLUMNS, columns="strategy_name", values="is_winner"
    )
    vector = (
        winners.reindex(columns=VECTOR_TUNED_STRATEGIES).eq(True).any(axis=1)
    )
    voronoi = winners.reindex(columns=VORONOI_STRATEGIES).eq(True).any(axis=1)
    categories = {
        "VectorOnly": vector & ~voronoi,
        "Both": vector & voronoi,
        "VoronoiOnly": ~vector & voronoi,
        "Neither": ~vector & ~voronoi,
    }
    denominator = len(winners)
    return pd.DataFrame(
        [
            {
                "category": category,
                "count": int(mask.sum()),
                "denominator": denominator,
                "percent": 100 * mask.sum() / denominator
                if denominator
                else 0.0,
            }
            for category, mask in categories.items()
        ]
    )


def render_family_rates(splits: dict[str, pd.DataFrame]) -> str:
    """Render one macro per (family, category), rounded once."""
    lines = [
        "% Generated by experiments.analysis.generate_decision_summaries."
    ]
    for family, split in splits.items():
        prefix = "Multiclass" + ("Cost" if family == "cost" else "Metric")
        denominator = int(split["denominator"].iloc[0])
        lines.append(rf"\newcommand{{\{prefix}CellCount}}{{{denominator}}}")
        for row in split.itertuples(index=False):
            lines.append(
                rf"% {row.category}: {row.count}/{row.denominator} cells."
            )
            lines.append(
                rf"\newcommand{{\{prefix}{row.category}}}"
                rf"{{{format_percent(row.percent)}\%}}"
            )
    return "\n".join(lines) + "\n"


def write_decision_summaries(
    parquet_path: Path | None = None, tables_dir: Path = TABLES_DIR
) -> Path:
    """Apply the same filters as the win-count figures and write macros."""
    cfg = SCOPE_CONFIG["multiclass"]
    path = parquet_path or _find_latest_parquet(cfg["parquet_pattern"])
    print(f"Reading: {path}")
    df = _normalize_balanced_error_objective(
        _apply_legacy_strategy_renames(pd.read_parquet(path))
    )
    df = _drop_custom_cost_fallback(df)
    df = df[df["dataset_name"].isin(cfg["datasets"])]
    splits = {}
    for family, objectives in (
        ("cost", cfg["cost_objectives"]),
        ("max", cfg["max_metrics"]),
    ):
        sub = df[df["optimization_objective_name"].isin(objectives)]
        splits[family] = compute_winning_family_split(
            compute_win_table(sub, cfg["max_metrics"])
        )
    tables_dir.mkdir(parents=True, exist_ok=True)
    output = tables_dir / OUTPUT_NAME
    output.write_text(render_family_rates(splits), encoding="utf-8")
    print(f"  Wrote {output}")
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path)
    parser.add_argument("--output", type=Path, default=TABLES_DIR)
    args = parser.parse_args()
    write_decision_summaries(args.results, args.output)


if __name__ == "__main__":
    main()
